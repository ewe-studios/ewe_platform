//! Client-facing auth: signed bootstrap secret → client certificate → mutual
//! TLS, with a durable record of every enrolled client.
//!
//! WHY: agent-rpc owns how its clients authenticate (spec 83: the proxy never
//! sees this channel). A client starts with nothing but a signed, time-boxed
//! secret handed to it out of band; after one enrollment it holds a
//! certificate, and from then on every call is authenticated by mutual TLS
//! (mTLS) against the trusted-client store.
//!
//! WHAT:
//! - [`MtlsConfig`] — the certificate authority (CA) of spec 87, the
//!   bootstrap-secret signer ([`crate::secret::BootstrapSecrets`]), the trust
//!   store of spec 87, certificate lifetimes, server names and enrollment
//!   policy (limits are fields with documented defaults).
//!   [`MtlsConfig::from_state_dir`] loads or creates all of it in one place.
//! - [`EnrollmentService`] — the generated `BootstrapService`: verify the
//!   secret, spend one use, sign the certificate signing request (CSR), record
//!   the client.
//! - TLS server configs for the two listeners (server-auth bootstrap,
//!   mutual-TLS agent listener), built by `foundation_auth::mtls`.
//!
//! HOW: the agent listener's `rustls` config requires a client certificate
//! that chains to the CA **and** is in the trust store, not revoked, so a call
//! without one fails in the handshake and no request reaches a handler. The
//! bootstrap listener serves only `Enroll`.

