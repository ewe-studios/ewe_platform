// TLS listeners

/// The two TLS acceptors of a secure server plus what clients pin.
pub(crate) struct TlsListeners {
    pub(crate) agent: Arc<SSLAcceptor>,
    pub(crate) bootstrap: Arc<SSLAcceptor>,
    pub(crate) fingerprint_sha256: String,
}

pub(crate) fn tls_listeners(config: &MtlsConfig) -> AgentRpcResult<TlsListeners> {
    let server_key = CaKey::generate(config.ca.config().key_algorithm, &config.ctx)
        .map_err(|e| pki_error(&e))?;
    let identity = config
        .ca
        .issue_server_identity(
            &server_key,
            &config.server_names,
            config.server_cert_lifetime,
        )
        .map_err(|e| pki_error(&e))?;
    let agent = server_config_mutual(&identity, &config.ca, config.trusted.index(), &config.ctx)
        .map_err(|e| pki_error(&e))?;
    let bootstrap = server_config_server_auth(&identity, &config.ctx).map_err(|e| pki_error(&e))?;
    Ok(TlsListeners {
        agent: Arc::new(SSLAcceptor::with_config(agent)),
        bootstrap: Arc::new(SSLAcceptor::with_config(bootstrap)),
        fingerprint_sha256: identity.fingerprint_sha256().to_string(),
    })
}
