//! Build pipeline — source scanner and code generation orchestrator.
//!
//! Two entry points:
//!
//! 1. `generate_platform_code()` — called from `src-tauri/build.rs`.
//!    Runs `tauri_build::build()`, scans `src/` for platform annotations.
//!
//! 2. `build_wasm_app(app_dir, public_dir)` — called from root `build.rs`.
//!    Scans `app/src/` for `#[wasm_bin]` / `#[wasm_worker]` /
//!    `#[wasm_service]` via text scanner, converts to `(mode, fn_name)`
//!    pairs, and delegates to `WasmBundleGenerator::from_annotations`.

use std::path::{Path, PathBuf};

// ── Entry point: src-tauri/build.rs ────────────────────────────────────

pub fn generate_platform_code() {
    tauri_build::build();

    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set"),
    );

    println!("cargo:rerun-if-changed=src/");
    println!("cargo:rerun-if-changed=build.rs");

    // Scan src-tauri/src/ for #[platform_bin]
    let annotations = scan_for_annotations(&manifest_dir.join("src"));
    for a in &annotations {
        if a.kind == AnnotationKind::PlatformBin {
            println!("cargo:warning=found #[platform_bin] '{}'", a.name);
        }
    }

    // Scan ../app/src/ for #[platform_bin] in the WASM crate
    let app_src = manifest_dir.parent().unwrap().join("app").join("src");
    if app_src.exists() {
        let app_annotations = scan_for_annotations(&app_src);
        for a in &app_annotations {
            if a.kind == AnnotationKind::PlatformBin {
                println!("cargo:warning=found #[platform_bin] '{}' in app/src/", a.name);
                generate_platform_main(&manifest_dir, &a.name);
            }
        }
    }

    let generated_dir = manifest_dir.join("src").join("generated");
    if !generated_dir.exists() {
        std::fs::create_dir_all(&generated_dir).ok();
        if !generated_dir.join("mod.rs").exists() {
            std::fs::write(
                generated_dir.join("mod.rs"),
                "// Auto-generated by foundation_platform::codegen\n",
            )
            .ok();
        }
    }
}

/// Generate `src-tauri/src/generated/main.rs` — wraps the user's
/// `#[platform_bin]` function with the Tauri entrypoint boilerplate.
fn generate_platform_main(manifest_dir: &Path, fn_name: &str) {
    let generated_dir = manifest_dir.join("src").join("generated");
    std::fs::create_dir_all(&generated_dir).ok();

    let content = format!(
        r#"// Generated by foundation_platform::codegen — #[platform_bin] "{fn_name}"
// Called from src-tauri/src/lib.rs via: platform_bin_run!();

use foundation_platform::*;

/// Calls the user's #[platform_bin] function, passing the session
/// for route registration. Returns the configured PlatformBuilder.
pub fn platform_bin_setup(session: &PlatformSession) {{
    super::{fn_name}(session);
}}
"#
    );
    std::fs::write(generated_dir.join("platform_main.rs"), &content)
        .unwrap_or_else(|e| eprintln!("cargo:warning=failed to write platform_main.rs: {e}"));
    println!("cargo:warning=generated src/generated/platform_main.rs — call platform_bin_setup() from your setup hook");
}

// ── Entry point: root build.rs ─────────────────────────────────────────

/// Scans `app_dir/src/` for WASM annotations, converts each to a
/// `(mode, fn_name)` pair, and feeds them to `WasmBundleGenerator`.
///
/// `WasmBundleGenerator::from_annotations` builds `WasmEntrypoint`s
/// in memory, feeds them to the inner `WasmBinGenerator` which
/// generates `src/bin/{name}/main.rs` stubs + `[[bin]]` entries,
/// compiles each bin to wasm32, generates JS wrappers, and copies
/// runtimes to `public_dir/`.
pub fn build_wasm_app(app_dir: &Path, public_dir: &Path) {
    use foundation_wasm_ui::build_tools::WasmBundleGenerator;

    println!("cargo:rerun-if-changed=app/src/");
    println!("cargo:rerun-if-changed=app/Cargo.toml");

    let wasm_annotations: Vec<_> = scan_for_annotations(&app_dir.join("src"))
        .into_iter()
        .filter(|a| matches!(a.kind, AnnotationKind::WasmBin | AnnotationKind::WasmWorker | AnnotationKind::WasmService))
        .collect();

    if wasm_annotations.is_empty() {
        println!("cargo:warning=no wasm annotations in app/src/ — skipping");
        return;
    }

    println!(
        "cargo:warning=found {} wasm entrypoints: {:?}",
        wasm_annotations.len(),
        wasm_annotations.iter().map(|a| &*a.name).collect::<Vec<_>>()
    );

    let pairs: Vec<(&str, &str)> = wasm_annotations
        .iter()
        .map(|a| (mode_str(a.kind), a.name.as_str()))
        .collect();

    let generator = match WasmBundleGenerator::from_annotations(app_dir, public_dir, &pairs) {
        Ok(g) => g,
        Err(e) => {
            println!("cargo:warning=WasmBundleGenerator init failed: {e}");
            return;
        }
    };

    let repo_root = app_dir.parent().unwrap().parent().unwrap().parent().unwrap();
    let interceptor = repo_root.join("backends/foundation_wasm_ui/runtimes/platform-scheme-interceptor.js");
    let runtime_assets: &[(&str, &Path)] = &[("platform-scheme-interceptor.js", &interceptor)];

    match generator.execute(false, false, runtime_assets) {
        Ok(files) => println!("cargo:warning=generated {} files", files.len()),
        Err(e) => println!("cargo:warning=execute failed: {e}"),
    }

    // Generate index.html
    let bins: Vec<&str> = wasm_annotations
        .iter()
        .filter(|a| a.kind == AnnotationKind::WasmBin)
        .map(|a| a.name.as_str())
        .collect();
    if !bins.is_empty() {
        std::fs::write(public_dir.join("index.html"), generate_index_html(&bins))
            .expect("write index.html");
    }
}

fn mode_str(k: AnnotationKind) -> &'static str {
    match k {
        AnnotationKind::WasmBin => "wasm_bin",
        AnnotationKind::WasmWorker => "wasm_worker",
        AnnotationKind::WasmService => "wasm_service",
        AnnotationKind::PlatformBin => "platform_bin",
    }
}

fn generate_index_html(bins: &[&str]) -> String {
    let mut inits = String::new();
    for name in bins {
        inits.push_str(&format!(
            r#"<script type=module>import{{init}}from'./{name}.js';init()
.then(()=>document.getElementById('status').textContent='WASM active')
.catch(e=>document.getElementById('status').textContent='Error: '+e.message)</script>
"#
        ));
    }
    format!(
        r#"<!DOCTYPE html>
<html lang=en><head><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>
<title>Foundation Platform</title><style>
*{{margin:0;padding:0;box-sizing:border-box}}body{{font-family:sans-serif;padding:16px;background:#0a0a1a;color:#ccd6f6}}
h1{{color:#64ffda;font-size:22px}}p{{color:#8892b0;font-size:12px}}#status{{margin:12px 0;font-size:11px;color:#445566}}
</style></head><body><h1>Foundation Platform</h1><p>Android — WASM UI</p>
<div id=status>Loading...</div>{inits}</body></html>"#
    )
}

// ── Annotation scanning ────────────────────────────────────────────────

#[derive(Debug, Clone)]
pub struct Annotation {
    pub name: String,
    pub kind: AnnotationKind,
    pub file: PathBuf,
    pub target: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AnnotationKind {
    WasmBin,
    WasmWorker,
    WasmService,
    PlatformBin,
}

impl AnnotationKind {
    pub fn name(&self) -> &'static str {
        match self {
            AnnotationKind::WasmBin => "#[wasm_bin]",
            AnnotationKind::WasmWorker => "#[wasm_worker]",
            AnnotationKind::WasmService => "#[wasm_service]",
            AnnotationKind::PlatformBin => "#[platform_bin]",
        }
    }
}

pub fn scan_for_annotations(src_dir: &Path) -> Vec<Annotation> {
    let mut found = Vec::new();
    let Ok(entries) = std::fs::read_dir(src_dir) else { return found; };
    for entry in entries.filter_map(|e| e.ok()) {
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().map_or(false, |n| n != "target" && !n.to_string_lossy().starts_with('.')) {
                found.extend(scan_for_annotations(&path));
            }
        } else if path.extension().map_or(false, |e| e == "rs") {
            if let Ok(content) = std::fs::read_to_string(&path) {
                let lines: Vec<&str> = content.lines().collect();
                let mut i = 0;
                while i < lines.len() {
                    let t = lines[i].trim();
                    let (kind, target) = parse_annotation(t);
                    if let Some(kind) = kind {
                        let name = (i..lines.len()).find_map(|j| {
                            lines[j].find("fn ").map(|p| {
                                let a = &lines[j][p + 3..];
                                a.split(|c: char| !c.is_alphanumeric() && c != '_')
                                    .find(|s| !s.is_empty())
                                    .unwrap_or("unknown")
                                    .to_string()
                            })
                        });
                        if let Some(name) = name {
                            found.push(Annotation {
                                name,
                                kind,
                                file: path.clone(),
                                target: target.unwrap_or_else(|| "unknown".to_string()),
                            });
                        }
                    }
                    i += 1;
                }
            }
        }
    }
    found
}

fn parse_annotation(line: &str) -> (Option<AnnotationKind>, Option<String>) {
    let kind = if line.starts_with("#[wasm_bin") { Some(AnnotationKind::WasmBin) }
    else if line.starts_with("#[wasm_worker") { Some(AnnotationKind::WasmWorker) }
    else if line.starts_with("#[wasm_service") { Some(AnnotationKind::WasmService) }
    else if line.starts_with("#[platform_bin") { Some(AnnotationKind::PlatformBin) }
    else { None };
    let target = line.find("target").and_then(|i| {
        let rest = &line[i..];
        rest.find('"').and_then(|start| {
            let after = &rest[start + 1..];
            after.find('"').map(|end| after[..end].to_string())
        })
    });
    (kind, target)
}
