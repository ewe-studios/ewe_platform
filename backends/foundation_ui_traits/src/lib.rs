// ─── IntoHtml trait ──────────────────────────────────────────────────────────

/// Converts a value into an [`Html`] fragment.
///
/// Implemented for all common types so `{expr}` in `html!` works without
/// manual conversion.
pub trait IntoHtml {
    fn into_html(self) -> Html;
}

impl IntoHtml for Html {
    fn into_html(self) -> Html {
        self
    }
}

impl IntoHtml for Vec<Html> {
    fn into_html(self) -> Html {
        Html {
            tag: None,
            attributes: Vec::new(),
            children: self,
            text: None,
            parts: Vec::new(),
        }
    }
}

impl IntoHtml for Option<Html> {
    fn into_html(self) -> Html {
        match self {
            Some(html) => html,
            None => Html {
                tag: None,
                attributes: Vec::new(),
                children: Vec::new(),
                text: None,
                parts: Vec::new(),
            },
        }
    }
}

impl IntoHtml for &str {
    fn into_html(self) -> Html {
        Html {
            tag: None,
            attributes: Vec::new(),
            children: Vec::new(),
            text: Some(self.into()),
            parts: Vec::new(),
        }
    }
}

impl IntoHtml for String {
    fn into_html(self) -> Html {
        Html {
            tag: None,
            attributes: Vec::new(),
            children: Vec::new(),
            text: Some(self),
            parts: Vec::new(),
        }
    }
}

impl IntoHtml for &Html {
    fn into_html(self) -> Html {
        self.clone()
    }
}

// Primitives via Display
macro_rules! impl_into_html_for_display {
    ($($ty:ty),*) => {
        $(
            impl IntoHtml for $ty {
                fn into_html(self) -> Html {
                    Html {
                        tag: None,
                        attributes: Vec::new(),
                        children: Vec::new(),
                        text: Some(alloc::format!("{}", self)),
                        parts: Vec::new(),
                    }
                }
            }
        )*
    };
}

impl_into_html_for_display!(usize, isize, u8, u16, u32, u64, i8, i16, i32, i64, bool, f32, f64);

// ─── Html struct ─────────────────────────────────────────────────────────────

/// Lightweight DOM tree generated by the `html!` macro.
///
/// Not the arena-allocated `Fragment` from `foundation_html` — a simpler tree
/// for client-side use.
#[derive(Clone, Debug, PartialEq)]
pub struct Html {
    pub tag: Option<String>,
    pub attributes: Vec<(String, String)>,
    pub children: Vec<Html>,
    pub text: Option<String>,
    pub parts: Vec<Part>,
}

impl Html {
    #[must_use]
    pub fn new() -> Self {
        Self {
            tag: None,
            attributes: Vec::new(),
            children: Vec::new(),
            text: None,
            parts: Vec::new(),
        }
    }

    /// Returns true if this is a text node (no tag, has text content).
    #[must_use]
    pub fn is_text(&self) -> bool {
        self.tag.is_none() && self.text.is_some()
    }

    /// Returns true if this is an element node (has a tag).
    #[must_use]
    pub fn is_element(&self) -> bool {
        self.tag.is_some()
    }
}

impl Default for Html {
    fn default() -> Self {
        Self::new()
    }
}

// ─── Part descriptors ────────────────────────────────────────────────────────

/// Describes a dynamic slot in an [`Html`] tree.
///
/// Each `Part` becomes one `Effect` that reads a signal and queues a `DomOp`.
#[derive(Clone, Debug, PartialEq)]
pub enum Part {
    Text(TextPart),
    Attribute(AttrPart),
    Event(EventPart),
    Children(ChildPart),
}

/// A dynamic text content slot — `{signal}` inside an element.
#[derive(Clone, Debug, PartialEq)]
pub struct TextPart {
    /// The `primal-id` of the element containing this text slot.
    pub node_id: u32,
}

/// A dynamic attribute slot — `class={expr}`, `id={expr}`, etc.
#[derive(Clone, Debug, PartialEq)]
pub struct AttrPart {
    /// The `primal-id` of the element.
    pub node_id: u32,
    /// The attribute name being set dynamically.
    pub attr_name: String,
}

/// An event handler slot — `primal:onclick={handler}`, etc.
#[derive(Clone, Debug, PartialEq)]
pub struct EventPart {
    /// The `primal-id` of the element.
    pub node_id: u32,
    /// The event name (e.g., "click", "change", "submit").
    pub event_name: String,
}

/// A dynamic children slot — `{vec_of_html}`, `{iterator}`, etc.
#[derive(Clone, Debug, PartialEq)]
pub struct ChildPart {
    /// The `primal-id` of the parent element.
    pub parent_id: u32,
}

// ─── DomOp enum ──────────────────────────────────────────────────────────────

/// A single DOM operation to be encoded into a protocol batch.
///
/// Maps to Arrow operations (decision 010).
#[derive(Clone, Debug, PartialEq)]
pub enum DomOp {
    /// Set the text content of a node.
    SetText { node_id: u32, text: String },
    /// Set an attribute on a node.
    SetAttr {
        node_id: u32,
        name: String,
        value: String,
    },
    /// Set the class on a node (adds/replaces).
    SetClass { node_id: u32, class: String },
    /// Set a style property on a node.
    SetStyle {
        node_id: u32,
        prop: String,
        value: String,
    },
    /// Create a new element node.
    CreateEl {
        node_id: u32,
        tag: String,
        class: String,
    },
    /// Append a child to a parent.
    AppendChild { parent_id: u32, child_id: u32 },
    /// Remove a node.
    Remove { node_id: u32 },
    /// Insert a child before a reference node.
    InsertBefore {
        parent_id: u32,
        child_id: u32,
        ref_id: u32,
    },
    /// Replace an existing node with a new one.
    Replace { old_id: u32, new_id: u32 },
    /// Morph an existing node's children with new HTML.
    Morph { node_id: u32, html: String },
}

