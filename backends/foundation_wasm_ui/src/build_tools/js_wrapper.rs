//! WHY: Each execution mode (decision 014) needs different JS glue — main
//! thread instantiation, worker + host pair, or a service worker with fetch
//! interception (decision 017). Hand-writing it per app defeats the pipeline.
//!
//! WHAT: Pure template functions, one per mode (feature 10 §4) — unit
//! testable without building any WASM.
//!
//! HOW: The wrappers ride the OWNED runtime (`foundation-wasm.js` /
//! `foundation-wasm-ui.js`, decision 031): instantiate with `rt.web_abi`,
//! call `rt.init(instance)`, invoke the entrypoint export. The
//! `// __EWE_WASM_LOAD__` marker line is what the single-file bundler
//! replaces with embedded bytes.

// Hosted-prelude import: this module is target-gated (native-only) inside a no_std crate.
#[allow(unused_imports)]
use std::prelude::rust_2021::*;

/// The fetch-based load block (replaced by the bundler for single-file).
const FETCH_LOAD: &str = "  // __EWE_WASM_LOAD__\n  const wasmBytes = await (await fetch(WASM_URL)).arrayBuffer();";

/// The protocol-1 (columnar) → DOM wiring injected after `rt.init(instance)`.
const REGISTER_WASM_APP: &str =
    "  globalThis.FoundationWasmUiRuntime.registerWasmApp(rt);";

/// `wasm_bin` — main-thread wrapper (`{name}.js`).
#[must_use]
pub fn bin_wrapper(name: &str) -> String {
    bin_wrapper_with_bundle(name, false)
}

/// `wasm_bin` with jsruntime_single support.
///
/// When `use_bundle` is true, the entrypoint is loaded via dynamic `import()`
/// from a classic `<script>` tag, and `bundle.js` is already present as a
/// classic `<script src>` earlier in the HTML. The entrypoint must NOT
/// statically `import` bundle.js — static imports fail on Android WebView
/// through Tauri's custom protocol, and the import is unnecessary anyway
/// because `FoundationWasmRuntime` and `FoundationWasmUiRuntime` are already
/// installed on `globalThis` by the classic script.
#[must_use]
pub fn bin_wrapper_with_bundle(name: &str, use_bundle: bool) -> String {
    let imports = if use_bundle {
        "// FoundationWasmRuntime is on globalThis from bundle.js (loaded as <script> in HTML)"
    } else {
        "import './foundation-wasm-ui.js';\nimport './platform-scheme-interceptor.js';\nimport { FoundationWasm } from './foundation-wasm.js';"
    };
    let rt_setup = if use_bundle {
        "const rt = new globalThis.FoundationWasmRuntime.FoundationWasm();"
    } else {
        "const rt = new FoundationWasm();"
    };
    format!(
        r#"// Generated by ewe-wasm build — wasm_bin entrypoint "{name}".
{imports}

const WASM_URL = './{name}.wasm';

export async function init(importOverrides = {{}}) {{
{FETCH_LOAD}
  {rt_setup}
  const imports = {{ abi: {{ ...rt.web_abi, ...importOverrides }} }};
  const {{ instance }} = await WebAssembly.instantiate(wasmBytes, imports);
  rt.init(instance);
{REGISTER_WASM_APP}
  instance.exports.{name}();
  return {{ runtime: rt, instance }};
}}
"#
    )
}

/// `wasm_worker` — the worker-side file (`{name}-worker.js`).
#[must_use]
pub fn worker_wrapper(name: &str) -> String {
    format!(
        r#"// Generated by ewe-wasm build — wasm_worker "{name}" (worker side).
import './foundation-wasm-ui.js';
import './platform-scheme-interceptor.js';
import {{ FoundationWasm }} from './foundation-wasm.js';

const WASM_URL = './{name}.wasm';

(async () => {{
{FETCH_LOAD}
  const rt = new FoundationWasm();
  const {{ instance }} = await WebAssembly.instantiate(wasmBytes, {{ abi: rt.web_abi }});
  rt.init(instance);
  instance.exports.{name}();
  self.postMessage({{ ready: true }});
  self.onmessage = (event) => {{
    // Host messages flow through the owned protocol layer.
    rt.dispatchHostMessage?.(event.data);
  }};
}})();
"#
    )
}

/// `wasm_worker` — the main-thread host (`{name}-worker-host.js`).
#[must_use]
pub fn worker_host(name: &str) -> String {
    format!(
        r#"// Generated by ewe-wasm build — wasm_worker "{name}" (host side).
export function start(workerUrl = './{name}-worker.js') {{
  const worker = new Worker(workerUrl, {{ type: 'module' }});
  const ready = new Promise((resolve) => {{
    worker.addEventListener('message', function onReady(event) {{
      if (event.data && event.data.ready) {{
        worker.removeEventListener('message', onReady);
        resolve();
      }}
    }});
  }});
  return {{
    worker,
    ready,
    send: (data) => worker.postMessage(data),
    terminate: () => worker.terminate(),
  }};
}}
"#
    )
}

/// `wasm_service` — service worker with fetch interception (`{name}-sw.js`).
#[must_use]
pub fn service_wrapper(name: &str, routes: &[String]) -> String {
    let route_list = routes
        .iter()
        .map(|r| format!("'{r}'"))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"// Generated by ewe-wasm build — wasm_service "{name}" (decision 017).
importScripts('./foundation-wasm.js');

const WASM_URL = './{name}.wasm';
const ROUTES = [{route_list}];

let runtimePromise = null;
async function ensureRuntime() {{
  if (!runtimePromise) {{
    runtimePromise = (async () => {{
{FETCH_LOAD}
      const rt = new globalThis.FoundationWasmRuntime.FoundationWasm();
      const {{ instance }} = await WebAssembly.instantiate(wasmBytes, {{ abi: rt.web_abi }});
      rt.init(instance);
      instance.exports.{name}();
      return rt;
    }})();
  }}
  return runtimePromise;
}}

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (event) => {{
  const url = new URL(event.request.url);
  if (!ROUTES.some((route) => url.pathname.startsWith(route))) {{
    return; // pass through — not ours
  }}
  event.respondWith(
    ensureRuntime().then((rt) => rt.handleServiceRequest(event.request)),
  );
}});
"#
    )
}

/// The marker the bundler replaces.
#[must_use]
pub fn load_marker() -> &'static str {
    FETCH_LOAD
}
