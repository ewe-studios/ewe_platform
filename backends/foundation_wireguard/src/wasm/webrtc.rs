//! WebRTC offerer — browser side (spec-55, F07).
//!
//! WHY: When NAT permits, browser peers upgrade from WebSocket relay to a direct
//! WebRTC data channel — lower latency, peer-to-peer, no relay hop.
//!
//! WHAT: [`WebRtcOfferer`] — creates an SDP offer, processes the answer, and
//! exposes a data channel that replaces the relay WebSocket as the WG transport.
//!
//! HOW: Signaling (SDP offer/answer + ICE candidates) rides the gossip RPC channel
//! — no separate signaling server. In wasm, `web_sys::RtcPeerConnection` is used;
//! on native test builds, the interface is stubbed.

/// A WebRTC offerer (browser side).
///
/// WHY: The browser always initiates the WebRTC connection — it has no UDP socket
/// to be "called" on. The native peer always answers.
pub struct WebRtcOfferer {
    /// The SDP offer string (generated by the browser's RTCPeerConnection).
    local_sdp: Option<String>,
    /// The remote SDP answer (from the native peer).
    remote_sdp: Option<String>,
    /// Whether the data channel is open.
    connected: bool,
}

impl WebRtcOfferer {
    /// Create a new offerer.
    #[must_use]
    pub fn new() -> Self {
        Self {
            local_sdp: None,
            remote_sdp: None,
            connected: false,
        }
    }

    /// WHY: The browser creates an SDP offer and sends it via gossip to the
    /// native peer.
    ///
    /// WHAT: Store the locally-generated SDP offer. In wasm, this is generated
    /// by `web_sys::RtcPeerConnection::create_offer()`.
    pub fn set_local_offer(&mut self, sdp: String) {
        self.local_sdp = Some(sdp);
    }

    /// The local SDP offer, ready to send via gossip.
    #[must_use]
    pub fn local_sdp(&self) -> Option<&str> {
        self.local_sdp.as_deref()
    }

    /// WHY: The native peer responds with an SDP answer via gossip.
    ///
    /// WHAT: Store the remote answer. In wasm, this is fed to
    /// `web_sys::RtcPeerConnection::set_remote_description()`.
    pub fn on_answer(&mut self, sdp: String) {
        self.remote_sdp = Some(sdp);
    }

    /// The remote SDP answer.
    #[must_use]
    pub fn remote_sdp(&self) -> Option<&str> {
        self.remote_sdp.as_deref()
    }

    /// Mark the data channel as open (called from JS callback).
    pub fn on_data_channel_open(&mut self) {
        self.connected = true;
    }

    /// Whether the WebRTC data channel is open and ready.
    #[must_use]
    pub fn is_connected(&self) -> bool {
        self.connected
    }
}

impl Default for WebRtcOfferer {
    fn default() -> Self {
        Self::new()
    }
}
