//! WebRTC offerer — browser side (spec-55, F07).
//!
//! WHY: When NAT permits, browser peers upgrade from WebSocket relay to a
//! direct WebRTC data channel — lower latency, peer-to-peer, no relay hop.
//!
//! WHAT: [`WebRtcOfferer`] — creates an SDP offer, processes the answer,
//! exchanges ICE candidates, and exposes a data channel transport that
//! replaces the relay WebSocket as the WG packet transport.
//!
//! HOW: Signaling (SDP offer/answer + ICE candidates) rides the SWIM gossip
//! channel via `SwimMessage::WebRtcSignal`. On the browser, the JS
//! `RTCPeerConnection` creates the offer and generates ICE candidates.
//! This Rust module provides the signaling state machine; the JS bridge
//! feeds SDP/ICE events into it and reads outbound signaling messages.

use crate::shared::membership::PeerId;
use crate::shared::webrtc::{OffererState, WebRtcSignal};

/// A WebRTC offerer (browser side).
///
/// The browser always initiates — it has no UDP socket to be "called" on.
/// This state machine tracks SDP offer/answer, ICE candidate exchange,
/// and the connection lifecycle. The JS bridge calls into these methods
/// when `RTCPeerConnection` events fire.
pub struct WebRtcOfferer {
    /// Current connection state.
    pub state: OffererState,
    /// The native peer we're connecting to.
    peer: Option<PeerId>,
    /// The SDP offer string (generated by the browser's RTCPeerConnection).
    local_sdp: Option<String>,
    /// The remote SDP answer (from the native peer).
    remote_sdp: Option<String>,
    /// Local ICE candidates (from the browser's RTCPeerConnection).
    local_candidates: Vec<String>,
    /// Remote ICE candidates (from the native peer via gossip).
    remote_candidates: Vec<String>,
}

impl Default for WebRtcOfferer {
    fn default() -> Self {
        Self::new()
    }
}

impl WebRtcOfferer {
    /// Create a new offerer in Idle state.
    #[must_use]
    pub fn new() -> Self {
        Self {
            state: OffererState::Idle,
            peer: None,
            local_sdp: None,
            remote_sdp: None,
            local_candidates: Vec::new(),
            remote_candidates: Vec::new(),
        }
    }

    /// Begin a WebRTC connection to a native peer.
    /// The JS bridge calls `RTCPeerConnection::create_offer()` and feeds
    /// the resulting SDP to this method.
    pub fn initiate(&mut self, peer: PeerId, sdp_offer: String) {
        self.peer = Some(peer);
        self.local_sdp = Some(sdp_offer);
        self.state = OffererState::OfferSent;
    }

    /// The local SDP offer, ready to send via gossip.
    #[must_use]
    pub fn local_offer(&self) -> Option<&str> {
        self.local_sdp.as_deref()
    }

    /// Process an SDP answer received from the native peer via gossip.
    /// The JS bridge feeds this to `RTCPeerConnection::set_remote_description()`.
    pub fn on_answer(&mut self, sdp: String) -> Option<String> {
        if self.state != OffererState::OfferSent {
            return None;
        }
        self.remote_sdp = Some(sdp.clone());
        self.state = OffererState::WaitingForAnswer;
        Some(sdp)
    }

    /// Add a local ICE candidate from the browser's RTCPeerConnection.
    /// Returns the serialized WebRtcSignal to send via gossip.
    pub fn add_local_candidate(&mut self, candidate: String, mid: Option<String>, mline: Option<u16>) -> Option<Vec<u8>> {
        if self.state != OffererState::WaitingForAnswer && self.state != OffererState::IceExchange {
            return None;
        }
        self.local_candidates.push(candidate.clone());
        if self.state == OffererState::WaitingForAnswer {
            self.state = OffererState::IceExchange;
        }
        let signal = WebRtcSignal::IceCandidate {
            candidate,
            sdp_mid: mid,
            sdp_mline_index: mline,
        };
        Some(signal.to_bytes())
    }

    /// Process an ICE candidate received from the native peer via gossip.
    /// The JS bridge feeds this to `RTCPeerConnection::add_ice_candidate()`.
    pub fn on_ice_candidate(&mut self, candidate: String, _mid: Option<String>, _mline: Option<u16>) {
        self.remote_candidates.push(candidate);
        if self.state == OffererState::WaitingForAnswer {
            self.state = OffererState::IceExchange;
        }
    }

    /// Called when the JS `RTCPeerConnection`'s `oniceconnectionstatechange`
    /// fires with "connected" — the data channel is open.
    pub fn on_connected(&mut self) {
        self.state = OffererState::Connected;
    }

    /// Called on failure or timeout.
    pub fn on_failure(&mut self) {
        self.state = OffererState::Failed;
    }

    /// The peer this offerer is connecting to.
    #[must_use]
    pub fn peer(&self) -> Option<PeerId> {
        self.peer
    }

    /// Whether the data channel is established.
    #[must_use]
    pub fn is_connected(&self) -> bool {
        self.state == OffererState::Connected
    }

    /// The remote SDP answer (to feed to RTCPeerConnection::set_remote_description).
    #[must_use]
    pub fn remote_sdp(&self) -> Option<&str> {
        self.remote_sdp.as_deref()
    }

    /// All local ICE candidates collected so far.
    #[must_use]
    pub fn local_candidates(&self) -> &[String] {
        &self.local_candidates
    }
}
