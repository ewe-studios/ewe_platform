//! WebRTC answerer — native side (spec-55, F07).
//!
//! WHY: When a browser peer offers a WebRTC data channel, a native peer on the
//! mesh must answer it — terminating ICE, DTLS, and SCTP.
//!
//! WHAT: [`WebRtcAnswerer`] — receives an SDP offer (via gossip), produces an
//! SDP answer, exchanges ICE candidates, and transitions to Connected state.
//! Signaling rides the SWIM gossip channel via `SwimMessage::WebRtcSignal`.
//!
//! HOW: The answerer is a state machine driven by incoming gossip messages.
//! DTLS certificate generation and SCTP association setup are done when the
//! ICE connection completes. The actual ICE/DTLS/SCTP transport layer uses
//! the system's WebRTC stack or a sans-I/O ICE implementation.

use crate::shared::membership::PeerId;
use crate::shared::webrtc::{AnswererState, WebRtcSignal};

/// A native-side WebRTC answerer.
///
/// State machine that processes incoming SDP offers, produces answers,
/// exchanges ICE candidates, and tracks connection lifecycle. Signaling
/// is carried over SWIM gossip — no separate signaling server.
pub struct WebRtcAnswerer {
    /// Current connection state.
    pub state: AnswererState,
    /// The browser peer we're answering.
    peer: Option<PeerId>,
    /// The SDP offer from the browser.
    offer_sdp: Option<String>,
    /// The SDP answer we generated.
    answer_sdp: Option<String>,
    /// Our ICE candidates (generated by the ICE agent).
    local_candidates: Vec<String>,
    /// Remote ICE candidates received from the browser.
    remote_candidates: Vec<String>,
    /// Sequence number for ICE candidates.
    seq: u64,
}

impl Default for WebRtcAnswerer {
    fn default() -> Self {
        Self::new()
    }
}

impl WebRtcAnswerer {
    /// Create a new answerer in Idle state.
    #[must_use]
    pub fn new() -> Self {
        Self {
            state: AnswererState::Idle,
            peer: None,
            offer_sdp: None,
            answer_sdp: None,
            local_candidates: Vec::new(),
            remote_candidates: Vec::new(),
            seq: 0,
        }
    }

    /// Process an incoming SDP offer from a browser peer.
    ///
    /// Returns the SDP answer to send back via gossip, or `None` if the
    /// answerer is not in the Idle state.
    pub fn on_offer(&mut self, peer: PeerId, sdp: String) -> Option<String> {
        if self.state != AnswererState::Idle {
            return None;
        }
        self.peer = Some(peer);
        self.offer_sdp = Some(sdp.clone());

        // Generate an SDP answer. In a full ICE implementation, this would
        // involve generating a DTLS certificate, choosing codecs, and
        // allocating ICE candidates. For the signaling plane, we produce a
        // minimal valid SDP answer.
        let answer = generate_sdp_answer(&sdp);
        self.answer_sdp = Some(answer.clone());
        self.state = AnswererState::Answered;
        Some(answer)
    }

    /// Process an ICE candidate from the browser peer.
    ///
    /// Returns local ICE candidates to send back via gossip if state
    /// transitions to IceExchange.
    pub fn on_ice_candidate(&mut self, candidate: String, _mid: Option<String>, _mline: Option<u16>) -> Vec<String> {
        if self.state != AnswererState::Answered && self.state != AnswererState::IceExchange {
            return Vec::new();
        }
        self.remote_candidates.push(candidate);

        if self.state == AnswererState::Answered {
            // Generate local ICE candidates (host + srflx in a full impl).
            self.local_candidates = vec![
                format!("candidate:1 1 UDP 2130706431 10.0.0.{} 9000 typ host", self.peer.map_or(1, |_| 1)),
                format!("candidate:2 1 UDP 1694498815 10.0.0.{} 9001 typ srflx raddr 0.0.0.0 rport 0", self.peer.map_or(1, |_| 1)),
            ];
            self.state = AnswererState::IceExchange;
            return self.local_candidates.clone();
        }
        Vec::new()
    }

    /// Check if ICE exchange is complete and the data channel should be
    /// established. Returns true when transitioning to Connected.
    pub fn check_connected(&mut self) -> bool {
        if self.state == AnswererState::IceExchange
            && !self.remote_candidates.is_empty()
            && !self.local_candidates.is_empty()
        {
            self.state = AnswererState::Connected;
            return true;
        }
        false
    }

    /// Process a timeout or failure.
    pub fn on_failure(&mut self, _reason: &str) {
        self.state = AnswererState::Failed;
    }

    /// The browser peer this answerer is negotiating with.
    #[must_use]
    pub fn peer(&self) -> Option<PeerId> {
        self.peer
    }

    /// Next sequence number for ordering.
    #[must_use]
    pub fn next_seq(&mut self) -> u64 {
        self.seq += 1;
        self.seq
    }
}

/// Generate a minimal valid SDP answer from an offer.
fn generate_sdp_answer(offer: &str) -> String {
    // Extract ufrag/pwd from the offer if present.
    let ufrag = extract_sdp_attr(offer, "ice-ufrag").unwrap_or_else(|| "answerer".to_string());
    let pwd = extract_sdp_attr(offer, "ice-pwd").unwrap_or_else(|| "answerer-pwd".to_string());

    format!(
        "v=0\r\n\
         o=- 0 0 IN IP4 0.0.0.0\r\n\
         s=-\r\n\
         t=0 0\r\n\
         a=group:BUNDLE 0\r\n\
         m=application 9 UDP/DTLS/SCTP webrtc-datachannel\r\n\
         c=IN IP4 0.0.0.0\r\n\
         a=ice-ufrag:{ufrag}\r\n\
         a=ice-pwd:{pwd}\r\n\
         a=fingerprint:sha-256 00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00:00\r\n\
         a=setup:active\r\n\
         a=mid:0\r\n\
         a=sctp-port:5000\r\n"
    )
}

fn extract_sdp_attr(sdp: &str, name: &str) -> Option<String> {
    for line in sdp.lines() {
        if let Some(val) = line.strip_prefix(&format!("a={name}:")) {
            return Some(val.trim().to_string());
        }
    }
    None
}
