// Patched: upstream calls `.static_crt(true)` on every platform, which forces
// `/MT` on Windows even when the Rust target uses the dynamic C runtime. Here
// `cc` follows the target's `crt-static` feature, as every other C++ object in
// the link does (issue #772; see UPSTREAM.md).
#[cfg(feature = "cpp")]
#[cfg(not(target_os = "macos"))]
fn main() {
    cc::Build::new()
        .cpp(true)
        .flag("-std=c++11")
        .file("src/esaxx.cpp")
        .include("src")
        .compile("esaxx");
}

#[cfg(feature = "cpp")]
#[cfg(target_os = "macos")]
fn main() {
    cc::Build::new()
        .cpp(true)
        .flag("-std=c++11")
        .flag("-stdlib=libc++")
        .file("src/esaxx.cpp")
        .include("src")
        .compile("esaxx");
}

#[cfg(not(feature = "cpp"))]
fn main() {}
